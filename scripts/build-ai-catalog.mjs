// Writes supabase/functions/ai/catalog.ts from the app's own design data, so
// the Edge Function offers the model exactly the directions, composition
// patterns and typefaces the app can render.
// Run after changing src/design/skills.js, patterns.js or fonts.js: npm run catalog
import fs from "node:fs";
import { SKILLS, skillText } from "../src/design/skills.js";
import { PATTERNS, ANTI_PATTERNS, HERO_OBJECTS } from "../src/design/patterns.js";
import { FONTS } from "../src/design/fonts.js";

const catalog = {
  skills: SKILLS.map((s) => ({ id: s.id, name: s.name, bestFor: s.bestFor, defaults: s.defaults, text: skillText(s) })),
  patterns: Object.entries(PATTERNS).map(([id, p]) => ({ id, type: p.type, name: p.name, recipe: p.recipe })),
  antiPatterns: ANTI_PATTERNS,
  heroObjects: HERO_OBJECTS,
  typefaces: Object.entries(FONTS).map(([name, f]) => ({ name, kind: f.kind, role: f.role, feel: f.feel })),
};

const out = `// Generated by scripts/build-ai-catalog.mjs. Do not edit by hand.\nexport const CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\n`;
fs.writeFileSync(new URL("../supabase/functions/ai/catalog.ts", import.meta.url), out);
console.log(`catalog: ${catalog.skills.length} skills, ${catalog.patterns.length} patterns, ${catalog.typefaces.length} typefaces`);
