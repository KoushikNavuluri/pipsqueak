let fontCSSCache = null;

async function getFontCSS() {
  fontCSSCache ||= (async () => {
    try {
      const t = (await (await fetch(FONTS_URL)).text())
        .split(/\/\*\s*([\w-]+)\s*\*\//)
        .reduce((r, o, i, s) => {
          if (i % 2 === 1 && o === "latin") {
            r.push(s[i + 1]);
          }
          return r;
        }, []);
      let a = "";
      for (const r of t) {
        const o = r.match(/url\((https:[^)]+)\)/);
        if (!o) {
          continue;
        }
        const i = await (await fetch(o[1])).arrayBuffer();
        let s = "";
        const l = new Uint8Array(i);
        for (let u = 0; u < l.length; u += 32768) {
          s += String.fromCharCode.apply(null, l.subarray(u, u + 32768));
        }
        a += `${
          r
            .trim()
            .replace(o[1], "data:font/woff2;base64," + btoa(s))
            .split("}")[0]
        }}
`;
      }
      return a;
    } catch {
      return "";
    }
  })();
  return fontCSSCache;
}

export async function elementToPng(e, t, a, r = 2) {
  const o = document.createElement("div");
  o.style.cssText = `position:fixed;left:-10000px;top:0;width:${t}px;height:${a}px;pointer-events:none;`;
  document.body.appendChild(o);
  const i = createRoot(o);
  i.render(e);
  await new Promise((u) => setTimeout(u, 80));
  try {
    await document.fonts?.ready;
  } catch {}
  await new Promise((u) =>
    requestAnimationFrame(() => requestAnimationFrame(u)),
  );
  const s = await getFontCSS();
  const l = await toBlob(o.firstElementChild || o, {
    width: t,
    height: a,
    pixelRatio: r,
    fontEmbedCSS: s,
  });
  i.unmount();
  o.remove();
  return l;
}

export async function zipBlobs(e) {
  const t = {};
  for (const [a, r] of e) {
    t[a] = new Uint8Array(await r.arrayBuffer());
  }
  return new Blob(
    [
      zipSync(t, {
        level: 0,
      }),
    ],
    {
      type: "application/zip",
    },
  );
}
